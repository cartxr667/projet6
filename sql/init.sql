
-- =========================================
-- 1. TYPE ENUMERATION
-- =========================================

CREATE TYPE statut_inscription AS ENUM (
    'inscrit',
    'valide',
    'abandon'
);

-- =========================================
-- 2. TABLE ETUDIANTS
-- =========================================

CREATE TABLE etudiants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricule VARCHAR(30) UNIQUE NOT NULL,
    nom VARCHAR(100) NOT NULL,
    prenom VARCHAR(100) NOT NULL,
    date_naissance DATE,
    email VARCHAR(150) UNIQUE,
    cree_le TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- =========================================
-- 3. TABLE FILIERES
-- =========================================

CREATE TABLE filieres (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(20) UNIQUE NOT NULL,
    libelle VARCHAR(150) NOT NULL,
    description TEXT
);

-- =========================================
-- 4. TABLE MATIERES
-- =========================================

CREATE TABLE matieres (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    filiere_id BIGINT NOT NULL,
    code VARCHAR(30) UNIQUE NOT NULL,
    libelle VARCHAR(150) NOT NULL,
    credits INTEGER NOT NULL CHECK (credits BETWEEN 1 AND 30),

    CONSTRAINT fk_matiere_filiere
        FOREIGN KEY (filiere_id)
        REFERENCES filieres(id)
        ON DELETE RESTRICT,

    CONSTRAINT uq_matiere_id_filiere
        UNIQUE (id, filiere_id)
);

-- =========================================
-- 5. TABLE INSCRIPTIONS
-- =========================================

CREATE TABLE inscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    etudiant_id BIGINT NOT NULL,
    matiere_id BIGINT NOT NULL,
    filiere_id BIGINT NOT NULL,
    annee INTEGER NOT NULL CHECK (annee BETWEEN 2000 AND 2100),
    statut statut_inscription DEFAULT 'inscrit',
    cree_le TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_inscription_etudiant
        FOREIGN KEY (etudiant_id)
        REFERENCES etudiants(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_inscription_matiere_filiere
        FOREIGN KEY (matiere_id, filiere_id)
        REFERENCES matieres(id, filiere_id)
        ON DELETE RESTRICT,

    CONSTRAINT uq_inscription
        UNIQUE (etudiant_id, matiere_id, annee)
);

-- =========================================
-- 6. TABLE NOTES
-- =========================================

CREATE TABLE notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inscription_id BIGINT NOT NULL,
    valeur NUMERIC(4,2) NOT NULL CHECK (valeur BETWEEN 0 AND 20),
    session VARCHAR(20) NOT NULL
        CHECK (session IN ('normale', 'rattrapage')),
    saisie_le TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    saisie_par VARCHAR(100) NOT NULL DEFAULT CURRENT_USER,

    CONSTRAINT fk_note_inscription
        FOREIGN KEY (inscription_id)
        REFERENCES inscriptions(id)
        ON DELETE CASCADE,

    CONSTRAINT uq_note_session
        UNIQUE (inscription_id, session)
);

-- =========================================
-- 7. TABLE AUDIT_NOTES
-- =========================================

CREATE TABLE audit_notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    note_id BIGINT NOT NULL,
    action VARCHAR(10) NOT NULL
        CHECK (action IN ('INSERT', 'UPDATE', 'DELETE')),
    ancienne_val NUMERIC(4,2),
    nouvelle_val NUMERIC(4,2),
    modifie_le TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    modifie_par VARCHAR(100) DEFAULT CURRENT_USER
);

-- =========================================
-- 8. FONCTION D'AUDIT
-- =========================================

CREATE OR REPLACE FUNCTION fn_audit_notes()
RETURNS TRIGGER AS $$
BEGIN

    IF TG_OP = 'INSERT' THEN

        INSERT INTO audit_notes (
            note_id,
            action,
            nouvelle_val,
            modifie_par
        )
        VALUES (
            NEW.id,
            'INSERT',
            NEW.valeur,
            NEW.saisie_par
        );

        RETURN NEW;

    ELSIF TG_OP = 'UPDATE' THEN

        INSERT INTO audit_notes (
            note_id,
            action,
            ancienne_val,
            nouvelle_val,
            modifie_par
        )
        VALUES (
            OLD.id,
            'UPDATE',
            OLD.valeur,
            NEW.valeur,
            CURRENT_USER
        );

        RETURN NEW;

    ELSIF TG_OP = 'DELETE' THEN

        INSERT INTO audit_notes (
            note_id,
            action,
            ancienne_val,
            modifie_par
        )
        VALUES (
            OLD.id,
            'DELETE',
            OLD.valeur,
            CURRENT_USER
        );

        RETURN OLD;

    END IF;

    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

-- =========================================
-- 9. DECLENCHEUR D'AUDIT
-- =========================================

CREATE TRIGGER trg_audit_notes
AFTER INSERT OR UPDATE OR DELETE
ON notes
FOR EACH ROW
EXECUTE FUNCTION fn_audit_notes();

-- =========================================
-- 10. VUE STATISTIQUES DES NOTES
-- =========================================

CREATE VIEW v_stats_notes AS
SELECT
    f.libelle AS filiere,
    m.libelle AS matiere,
    i.annee,
    COUNT(n.id) AS nombre_notes,
    ROUND(AVG(n.valeur), 2) AS moyenne,
    MIN(n.valeur) AS note_minimale,
    MAX(n.valeur) AS note_maximale

FROM notes n
JOIN inscriptions i ON n.inscription_id = i.id
JOIN matieres m ON i.matiere_id = m.id
JOIN filieres f ON m.filiere_id = f.id

GROUP BY f.libelle, m.libelle, i.annee;

-- =========================================
-- 11. VUE SUIVI DE LA REPLICATION
-- =========================================

CREATE VIEW v_retard_replication AS
SELECT
    application_name,
    client_addr,
    state,
    sync_state,
    write_lag,
    flush_lag,
    replay_lag
FROM pg_stat_replication;

-- =========================================
-- 12. INDEX POUR LES PERFORMANCES
-- =========================================

CREATE INDEX idx_matiere_filiere
ON matieres(filiere_id);

CREATE INDEX idx_inscription_etudiant
ON inscriptions(etudiant_id);

CREATE INDEX idx_inscription_matiere_annee
ON inscriptions(matiere_id, annee);

CREATE INDEX idx_inscription_filiere
ON inscriptions(filiere_id);

CREATE INDEX idx_notes_inscription
ON notes(inscription_id);

CREATE INDEX idx_audit_note
ON audit_notes(note_id);

